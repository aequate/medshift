"""Deterministic schema automaton + greedy constrained decoding for V3.2.

The automaton recognizes exactly:

    "TRIAGE: " <level-word> <free triage statement> "\\n"
    "1. " <free diagnosis text (>= 1 token)> "\\n"

where <level-word> is one of Emergency / Urgent / Urgent or emergency /
Non-urgent (each already maps onto the frozen triage keyword ladder) and the
free text is generated by the model in the usual greedy way.

Design notes:

* ``feed`` is called once per DECODED TOKEN (the runner decodes token by
  token). Inside ``feed`` the automaton drains its pending buffer greedily
  and repeatedly until no more progress is possible, so fused tokens (e.g. a
  newline token carrying the start of the next line, or a multi-character
  piece) are handled by the same code path as clean splits.
* Scaffolding phases are STRICT: pending text that neither extends nor
  matches the required literal raises ``SchemaDivergenceError``. In the GPU
  runner this is a fail-closed protocol violation; the compliant path can
  never hit it because the logits mask forbids non-conforming tokens while
  the automaton is in a scaffold phase.
* The level-word phase is entered with the model free to pick exactly one of
  the four frozen level words; "Urgent" / "Urgent or emergency" share the
  first token, so they are one branch whose " or emergency" extension is
  OPTIONAL free-ish text inside the level-word buffer until the newline:
  the frozen parser maps both variants correctly
  ("Urgent ..." -> prompt_clinical_assessment unless "emergency" also
  appears, in which case prompt_or_emergency_assessment).
* ``schema_complete`` becomes True once the diagnosis line holds at least one
  free token; ``halt`` becomes True at the terminal newline. EOS remains
  disallowed before ``halt`` because the frozen protocol requires that newline.
* Pure python, torch-free: the exact protocol logic is CPU-testable.
"""

from __future__ import annotations

from typing import Any

from .constrained_compact import (
    DIAG_LINE_PREFIX,
    MIN_DIAG_FREE_TOKENS,
    TRIAGE_BRANCHES,
    TRIAGE_LINE_PREFIX,
)

PREFIX_PHASE = "prefix"
LEVEL_WORD_PHASE = "level_word"
TRIAGE_FREE_PHASE = "triage_free"
DIAG_PREFIX_PHASE = "diag_prefix"
DIAG_FREE_PHASE = "diag_free"
COMPLETE_PHASE = "complete"

PHASES = (
    PREFIX_PHASE,
    LEVEL_WORD_PHASE,
    TRIAGE_FREE_PHASE,
    DIAG_PREFIX_PHASE,
    DIAG_FREE_PHASE,
    COMPLETE_PHASE,
)

# Level words that may continue with " or emergency" inside the level-word
# phase (shared-prefix branch, see module docstring).
EXTENSIBLE_LEVEL_WORDS = ("Urgent", "Urgent or emergency")


class SchemaDivergenceError(ValueError):
    """Model output left the frozen schema in a strict (scaffold) phase."""


class SchemaAutomaton:
    """Incremental recognizer/builder for the frozen V3.2 response schema."""

    def __init__(self) -> None:
        self._pending = ""  # decoded text not yet consumed by the automaton
        self.phase = PREFIX_PHASE
        self._level_word = ""
        self._diag_free_tokens = 0
        self.schema_complete = False
        self.halt = False

    # -- state ------------------------------------------------------------
    @property
    def level_word(self) -> str:
        return self._level_word

    def snapshot(self) -> dict[str, Any]:
        return {
            "phase": self.phase,
            "level_word": self._level_word,
            "diag_free_tokens": self._diag_free_tokens,
            "schema_complete": self.schema_complete,
            "halt": self.halt,
        }

    def constraint_state_key(self) -> tuple[Any, ...]:
        """Exact immutable state key for token-admissibility memoization.

        Include every mutable automaton component, not only ``phase``. This
        intentionally prevents partial scaffold prefixes from aliasing.
        """
        return (
            self.phase,
            self._pending,
            self._level_word,
            self._diag_free_tokens,
            self.schema_complete,
            self.halt,
        )

    # -- helpers -----------------------------------------------------------
    @staticmethod
    def _norm(chunk: str) -> str:
        """Normalize \r\n and stray \r so newline variants cannot desync."""
        return chunk.replace("\r\n", "\n").replace("\r", "\n")

    def _drain(self) -> None:
        """Repeatedly consume pending text according to the current phase."""
        progressed = True
        while progressed and self.phase != COMPLETE_PHASE:
            progressed = False
            pending = self._pending
            if self.phase == PREFIX_PHASE:
                if pending.startswith(TRIAGE_LINE_PREFIX):
                    self._pending = pending[len(TRIAGE_LINE_PREFIX) :]
                    self.phase = LEVEL_WORD_PHASE
                    progressed = True
                elif TRIAGE_LINE_PREFIX.startswith(pending):
                    pass  # need more tokens
                else:
                    raise SchemaDivergenceError(
                        f"expected {TRIAGE_LINE_PREFIX!r}, got {pending!r}"
                    )
            elif self.phase == LEVEL_WORD_PHASE:
                matched = False
                for branch in TRIAGE_BRANCHES:
                    for word in branch:
                        if pending.startswith(word):
                            # Exactly one branch word can be a prefix here:
                            # no branch word is a prefix of another.
                            self._level_word = word
                            self._pending = pending[len(word) :]
                            self.phase = TRIAGE_FREE_PHASE
                            progressed = True
                            matched = True
                            break
                    if matched:
                        break
                if not matched and not any(
                    w.startswith(pending) for b in TRIAGE_BRANCHES for w in b
                ):
                    raise SchemaDivergenceError(
                        f"expected a triage level word, got {pending!r}"
                    )
            elif self.phase == TRIAGE_FREE_PHASE:
                if "\n" in pending:
                    # Newline reached; everything after it (if fused) must
                    # start the diagnosis line, handled in DIAG_PREFIX_PHASE.
                    self._pending = pending.split("\n", 1)[1]
                    self.phase = DIAG_PREFIX_PHASE
                    progressed = True
                # else: free statement continues; wait for the newline.
            elif self.phase == DIAG_PREFIX_PHASE:
                if pending.startswith(DIAG_LINE_PREFIX):
                    self._pending = pending[len(DIAG_LINE_PREFIX) :]
                    self.phase = DIAG_FREE_PHASE
                    progressed = True
                elif DIAG_LINE_PREFIX.startswith(pending):
                    pass  # need more tokens (fused newline + "1" + ". " etc.)
                else:
                    raise SchemaDivergenceError(
                        f"expected {DIAG_LINE_PREFIX!r}, got {pending!r}"
                    )
            elif self.phase == DIAG_FREE_PHASE:
                if "\n" in pending:
                    head, _, tail = pending.partition("\n")
                    if head:
                        self._diag_free_tokens += 1
                    self._pending = ""
                    self._diag_free_tokens = max(self._diag_free_tokens, 1)
                    self.schema_complete = True
                    self.halt = True
                    self.phase = COMPLETE_PHASE
                    self._tail_after_halt = tail  # diagnostic only
                    progressed = True
                elif pending:
                    self._diag_free_tokens += 1
                    self._pending = ""
                    if self._diag_free_tokens >= MIN_DIAG_FREE_TOKENS:
                        self.schema_complete = True
                    progressed = True

    # -- incremental feed ---------------------------------------------------
    def feed(self, token_text: str) -> None:
        """Feed one decoded token (without special tokens)."""
        if self.phase == COMPLETE_PHASE:
            return  # halted; ignore anything after the terminal newline
        self._pending += self._norm(token_text)
        self._drain()

    # -- decoding queries ---------------------------------------------------
    def can_emit(self, token_text: str) -> bool:
        """Whether the automaton can accept this candidate next token."""
        candidate = self._pending + self._norm(token_text)
        if self.phase == PREFIX_PHASE:
            return TRIAGE_LINE_PREFIX.startswith(candidate)
        if self.phase == LEVEL_WORD_PHASE:
            return any(
                word.startswith(candidate) for b in TRIAGE_BRANCHES for word in b
            )
        if self.phase in (TRIAGE_FREE_PHASE, DIAG_FREE_PHASE):
            return True  # free text; EOS is gated separately by allow_eos()
        if self.phase == DIAG_PREFIX_PHASE:
            return DIAG_LINE_PREFIX.startswith(candidate)
        return False  # COMPLETE_PHASE: nothing more may be emitted

    def allow_eos(self) -> bool:
        """EOS is legal only after terminal-newline halt."""
        return self.halt


def build_automaton() -> SchemaAutomaton:
    return SchemaAutomaton()
